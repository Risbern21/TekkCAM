use crate::cam::{operations::Operation, toolpath::ToolMove};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Dialect {
    Grbl,
    LinuxCnc,
}

impl Dialect {
    pub fn label(self) -> &'static str {
        match self {
            Self::Grbl => "GRBL",
            Self::LinuxCnc => "LinuxCNC",
        }
    }
}

pub fn generate(operations: &[Operation], dialect: Dialect) -> Result<String, String> {
    let generated: Vec<_> = operations
        .iter()
        .filter(|op| op.generated && !op.toolpath.is_empty())
        .collect();
    if generated.is_empty() {
        return Err("Generate at least one toolpath first".into());
    }
    let mut out = vec![
        "( Generated by tekkCAM )".to_string(),
        "G21".into(),
        "G90".into(),
        "G17".into(),
        "G94".into(),
    ];
    for (index, op) in generated.iter().enumerate() {
        out.push(format!("\n( {} - {} )", op.name, op.tool.name));
        if dialect == Dialect::LinuxCnc {
            out.push(format!("T{} M6", index + 1));
        }
        if op.tool.spindle_rpm > 0.0 {
            out.push(format!("M3 S{}", fmt(op.tool.spindle_rpm)));
        }
        for movement in &op.toolpath.moves {
            match movement {
                ToolMove::Rapid { to, z } => {
                    // Retract before traversing so a rapid does not sweep through stock.
                    out.push("G0 Z5.000".into());
                    out.push(format!("G0 X{} Y{}", fmt(to[0]), fmt(to[1])));
                    if *z > 0.0 {
                        out.push(format!("G0 Z{}", fmt(*z)));
                    }
                }
                ToolMove::Feed { to, z, feed_mm_min } => out.push(format!(
                    "G1 X{} Y{} Z{} F{}",
                    fmt(to[0]),
                    fmt(to[1]),
                    fmt(*z),
                    fmt(*feed_mm_min)
                )),
                ToolMove::Arc {
                    to,
                    center_offset,
                    z,
                    clockwise,
                    feed_mm_min,
                } => out.push(format!(
                    "{} X{} Y{} Z{} I{} J{} F{}",
                    if *clockwise { "G2" } else { "G3" },
                    fmt(to[0]),
                    fmt(to[1]),
                    fmt(*z),
                    fmt(center_offset[0]),
                    fmt(center_offset[1]),
                    fmt(*feed_mm_min)
                )),
                ToolMove::Drill {
                    at,
                    depth,
                    retract,
                    plunge_mm_min,
                } => {
                    out.push(format!("G0 X{} Y{}", fmt(at[0]), fmt(at[1])));
                    out.push(format!("G1 Z{} F{}", fmt(*depth), fmt(*plunge_mm_min)));
                    out.push(format!("G0 Z{}", fmt(*retract)));
                }
            }
        }
        if op.tool.spindle_rpm > 0.0 {
            out.push("M5".into());
        }
    }
    out.extend(["G0 Z5.000".into(), "M30".into()]);
    Ok(out.join("\n") + "\n")
}

fn fmt(value: f64) -> String {
    let value = if value.abs() < 0.0005 { 0.0 } else { value };
    format!("{value:.3}")
}
