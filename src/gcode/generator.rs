use crate::cam::{operations::Operation, toolpath::ToolMove};
use crate::workspace::setup::MachiningSetup;

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub enum Dialect {
    #[default]
    Grbl,
    LinuxCnc,
}

impl Dialect {
    pub fn label(self) -> &'static str {
        match self {
            Self::Grbl => "GRBL",
            Self::LinuxCnc => "LinuxCNC",
        }
    }
}

pub fn generate(operations: &[Operation], dialect: Dialect) -> Result<String, String> {
    generate_with_setup(operations, dialect, &MachiningSetup::default())
}

pub fn generate_with_setup(
    operations: &[Operation],
    dialect: Dialect,
    setup: &MachiningSetup,
) -> Result<String, String> {
    setup.validate()?;
    let generated: Vec<_> = operations
        .iter()
        .filter(|op| op.generated && !op.toolpath.is_empty())
        .collect();
    if generated.is_empty() {
        return Err("Generate at least one toolpath first".into());
    }
    for operation in &generated {
        operation.tool.validate()?;
    }
    if let Some(limits) = &setup.machine_limits {
        validate_machine_limits(&generated, setup, limits)?;
    }
    let mut out = vec![
        "( Generated by tekkCAM )".to_string(),
        "G21".into(),
        "G90".into(),
        "G17".into(),
        "G94".into(),
        "M5".into(),
        setup.work_offset.code().into(),
    ];
    if setup.machine_limits.is_none() {
        out.push("( Machine travel limits are not configured; bounds were not verified )".into());
    }
    let safe_z = setup.safe_z_mm;
    let mut final_safe_z = safe_z;
    let mut previous_tool: Option<(&str, f64, crate::cam::tool::ToolShape)> = None;
    let mut tool_ids = Vec::new();
    for op in &generated {
        out.push(format!(
            "\n( {} - {} )",
            comment_text(&op.name),
            comment_text(&op.tool.name)
        ));
        let tool_key = (op.tool.name.as_str(), op.tool.diameter_mm, op.tool.shape);
        if previous_tool != Some(tool_key) {
            out.push(format!("G0 Z{}", fmt(safe_z)));
            let tool_number = tool_ids
                .iter()
                .position(|key| *key == tool_key)
                .map(|index| index + 1)
                .unwrap_or_else(|| {
                    tool_ids.push(tool_key);
                    tool_ids.len()
                });
            if dialect == Dialect::LinuxCnc {
                out.push(format!("T{} M6", tool_number));
            } else {
                out.push(format!(
                    "( Manual tool change: {} )",
                    comment_text(&op.tool.name)
                ));
                out.push("M0".into());
            }
            previous_tool = Some(tool_key);
        }
        if op.tool.spindle_rpm > 0.0 {
            out.push(format!("M3 S{}", fmt(op.tool.spindle_rpm)));
        }
        for movement in &op.toolpath.moves {
            match movement {
                ToolMove::Rapid { to, z } => {
                    // Retract before traversing so a rapid does not sweep through stock.
                    let target = program_point(*to, *z, setup);
                    let retract_z = safe_z.max(target[2]);
                    final_safe_z = final_safe_z.max(retract_z);
                    out.push(format!("G0 Z{}", fmt(retract_z)));
                    out.push(format!("G0 X{} Y{}", fmt(target[0]), fmt(target[1])));
                    if target[2] < retract_z {
                        out.push(format!("G0 Z{}", fmt(target[2])));
                    }
                }
                ToolMove::Feed { to, z, feed_mm_min } => {
                    let target = program_point(*to, *z, setup);
                    out.push(format!(
                        "G1 X{} Y{} Z{} F{}",
                        fmt(target[0]),
                        fmt(target[1]),
                        fmt(target[2]),
                        fmt(*feed_mm_min)
                    ));
                }
                ToolMove::Arc {
                    to,
                    center_offset,
                    z,
                    clockwise,
                    feed_mm_min,
                } => {
                    let target = program_point(*to, *z, setup);
                    out.push(format!(
                        "{} X{} Y{} Z{} I{} J{} F{}",
                        if *clockwise { "G2" } else { "G3" },
                        fmt(target[0]),
                        fmt(target[1]),
                        fmt(target[2]),
                        fmt(center_offset[0]),
                        fmt(center_offset[1]),
                        fmt(*feed_mm_min)
                    ));
                }
                ToolMove::Drill {
                    at,
                    depth,
                    retract,
                    plunge_mm_min,
                } => {
                    let target = program_point(*at, *depth, setup);
                    let retract_z = safe_z.max(*retract - setup.work_origin_mm[2]);
                    final_safe_z = final_safe_z.max(retract_z);
                    out.push(format!("G0 Z{}", fmt(retract_z)));
                    out.push(format!("G0 X{} Y{}", fmt(target[0]), fmt(target[1])));
                    out.push(format!("G1 Z{} F{}", fmt(target[2]), fmt(*plunge_mm_min)));
                    out.push(format!("G0 Z{}", fmt(retract_z)));
                }
            }
        }
        if op.tool.spindle_rpm > 0.0 {
            out.push("M5".into());
        }
    }
    out.extend([
        "M5".into(),
        format!("G0 Z{}", fmt(final_safe_z)),
        "M30".into(),
    ]);
    Ok(out.join("\n") + "\n")
}

fn comment_text(value: &str) -> String {
    value
        .chars()
        .map(|character| match character {
            '(' | ')' | '\n' | '\r' => ' ',
            other => other,
        })
        .collect()
}

fn program_point(xy: [f64; 2], z: f64, setup: &MachiningSetup) -> [f64; 3] {
    [
        xy[0] - setup.work_origin_mm[0],
        xy[1] - setup.work_origin_mm[1],
        z - setup.work_origin_mm[2],
    ]
}

fn validate_machine_limits(
    operations: &[&Operation],
    setup: &MachiningSetup,
    limits: &crate::workspace::setup::MachineLimits,
) -> Result<(), String> {
    limits.validate()?;
    if setup.safe_z_mm < limits.min_mm[2] || setup.safe_z_mm > limits.max_mm[2] {
        return Err(format!(
            "configured safe Z {:.3} mm exceeds machine Z limits [{:.3}, {:.3}] mm",
            setup.safe_z_mm, limits.min_mm[2], limits.max_mm[2]
        ));
    }
    let mut position = [0.0, 0.0, 0.0];
    let mut position_known = false;
    for operation in operations {
        for movement in &operation.toolpath.moves {
            match movement {
                ToolMove::Rapid { to, z } => {
                    let target = program_point(*to, *z, setup);
                    let retract_z = setup.safe_z_mm.max(target[2]);
                    if position_known {
                        limits.check_point([position[0], position[1], retract_z])?;
                    }
                    limits.check_point([target[0], target[1], retract_z])?;
                    limits.check_point(target)?;
                    position = target;
                    position_known = true;
                }
                ToolMove::Feed { to, z, .. } => {
                    if !position_known {
                        return Err(format!(
                            "operation '{}' starts with a cutting move; a rapid move is required before travel-limit verification",
                            operation.name
                        ));
                    }
                    position = program_point(*to, *z, setup);
                    limits.check_point(position)?;
                }
                ToolMove::Arc {
                    to,
                    center_offset,
                    z,
                    clockwise,
                    ..
                } => {
                    if !position_known {
                        return Err(format!(
                            "operation '{}' starts with an arc; a rapid move is required before travel-limit verification",
                            operation.name
                        ));
                    }
                    let target = program_point(*to, *z, setup);
                    let center = [
                        position[0] + center_offset[0],
                        position[1] + center_offset[1],
                    ];
                    let start_angle = (position[1] - center[1]).atan2(position[0] - center[0]);
                    let end_angle = (target[1] - center[1]).atan2(target[0] - center[0]);
                    let mut sweep = end_angle - start_angle;
                    if *clockwise {
                        while sweep >= 0.0 {
                            sweep -= std::f64::consts::TAU;
                        }
                    } else {
                        while sweep <= 0.0 {
                            sweep += std::f64::consts::TAU;
                        }
                    }
                    let radius = (position[0] - center[0]).hypot(position[1] - center[1]);
                    let samples = ((sweep.abs() / 5_f64.to_radians()).ceil() as usize).max(1);
                    for sample in 0..=samples {
                        let t = sample as f64 / samples as f64;
                        let angle = start_angle + sweep * t;
                        limits.check_point([
                            center[0] + radius * angle.cos(),
                            center[1] + radius * angle.sin(),
                            position[2] + (target[2] - position[2]) * t,
                        ])?;
                    }
                    limits.check_point(target)?;
                    position = target;
                }
                ToolMove::Drill {
                    at, depth, retract, ..
                } => {
                    let target = program_point(*at, *depth, setup);
                    let retract_z = setup.safe_z_mm.max(*retract - setup.work_origin_mm[2]);
                    if position_known {
                        limits.check_point([position[0], position[1], retract_z])?;
                    }
                    limits.check_point([target[0], target[1], retract_z])?;
                    limits.check_point(target)?;
                    position = [target[0], target[1], retract_z];
                    position_known = true;
                }
            }
        }
    }
    if position_known {
        limits.check_point([position[0], position[1], setup.safe_z_mm])?;
    }
    Ok(())
}

fn fmt(value: f64) -> String {
    let value = if value.abs() < 0.0005 { 0.0 } else { value };
    format!("{value:.3}")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cam::{operations::Operation, toolpath::Toolpath};

    #[test]
    fn rapid_retract_uses_the_requested_stock_clearance_height() {
        let mut operation = Operation::contour();
        operation.generated = true;
        operation.toolpath = Toolpath::default();
        operation.toolpath.push_rapid([12.0, 7.0], 27.0);
        let code = generate(&[operation], Dialect::Grbl).unwrap();
        assert!(code.contains("G0 Z27.000\nG0 X12.000 Y7.000"));
        assert!(code.ends_with("G0 Z27.000\nM30\n"));
    }
}
